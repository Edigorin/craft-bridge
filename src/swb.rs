//! The SWBasic/VBA emitter: a replay plan becomes a plain-text `.swb` macro.
//!
//! The generated macro mirrors `corpus/compat-check/minimal.swb`, the
//! hand-reviewed compatibility checkpoint: same entry point, same fresh-part
//! creation, same report contract (header first, one line per recipe step,
//! summary last, every line flushed). All untrusted text passes through the
//! VBA-literal escaper; report text gets its own JSON escaper inside the
//! macro. Numbers are emitted locale-independent.

use crate::replay::{
    AxisSel, DimKind, DimensionT, ExtrudeStep, OriginPlane, PlannedStep, RelationT, RevolveStep,
    SketchStep, Work,
};

/// VBA string-literal escaping: quotes doubled, control characters removed,
/// length capped. This is not JSON escaping; the macro has its own.
pub fn vb_lit(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars().take(200) {
        match c {
            '"' => out.push_str("\"\""),
            '\r' | '\n' | '\t' => out.push(' '),
            c if (c as u32) < 0x20 => out.push(' '),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A locale-independent VBA numeric literal (Rust's Display never uses
/// exponent notation; every value is validated finite upstream).
pub fn vba_num(v: f64) -> String {
    let s = v.to_string();
    if s.contains('.') || s.contains('e') || s.contains("inf") || s.contains("NaN") {
        s
    } else {
        format!("{s}.0")
    }
}

/// JSON string *content* escaping (backslash, quote, controls) for values
/// baked into generated JSON text. The result then goes through `vb_lit`
/// when it becomes part of a VBA literal: two separate escapes, never one.
pub fn json_str_content(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\r' => out.push_str("\\r"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {}
            c => out.push(c),
        }
    }
    out
}

fn plane_name(plane: OriginPlane) -> &'static str {
    match plane {
        OriginPlane::Xy => "Front Plane",
        OriginPlane::Xz => "Top Plane",
        OriginPlane::Yz => "Right Plane",
    }
}

fn mm(v: f64) -> f64 {
    v / 1000.0
}

/// Emit the whole macro for a plan. `steps` is the full plan in recipe order.
pub fn emit(steps: &[PlannedStep], artifact: &str, bridge_version: &str) -> String {
    let sketches: Vec<(usize, &SketchStep)> = steps
        .iter()
        .filter_map(|s| match &s.work {
            Work::Sketch(sk) => Some((s.index, sk)),
            _ => None,
        })
        .collect();
    let extrudes: Vec<(usize, &ExtrudeStep)> = steps
        .iter()
        .filter_map(|s| match &s.work {
            Work::Extrude(ex) => Some((s.index, ex)),
            _ => None,
        })
        .collect();

    let mut out = String::new();
    out.push_str(&format!(
        "' Generated by craft-bridge {bridge_version} from {} - review before running.\n",
        vb_lit(artifact)
    ));
    out.push_str("' Units: the SolidWorks API always takes metres and radians.\n");
    out.push_str("Option Explicit\n\n");
    out.push_str("Dim swApp As SldWorks.SldWorks\n");
    out.push_str("Dim swDoc As SldWorks.ModelDoc2\n");
    out.push_str("Dim swSketchMgr As SketchManager\n");
    out.push_str("Dim reportPath As String\n");
    out.push_str("Dim gMsg As String\n");
    let max_slot = steps
        .iter()
        .filter_map(|s| match &s.work {
            Work::Sketch(sk) => sk.dim_equations.iter().map(|(_, e)| e.slot).max(),
            Work::Extrude(ex) => ex.equations.iter().map(|e| e.slot).max(),
            Work::Revolve(rv) => rv.equations.iter().map(|e| e.slot).max(),
            Work::Primitive(pr) => pr
                .sizes
                .iter()
                .filter_map(|sz| sz.equation.as_ref().map(|e| e.slot))
                .max(),
            _ => None,
        })
        .max();
    if let Some(m) = max_slot {
        out.push_str(&format!("Dim regName(0 To {}) As String\n", m));
    }
    for s in steps {
        if matches!(
            s.work,
            Work::Extrude(_) | Work::Revolve(_) | Work::Primitive(_) | Work::Modifier(_)
        ) {
            out.push_str(&format!("Dim feat{} As SldWorks.Feature\n", s.index));
        }
    }
    for (index, sk) in &sketches {
        out.push_str(&format!("Dim skName{index} As String\n"));
        out.push_str(&format!(
            "Dim pt{index}(0 To {}) As SldWorks.SketchPoint\n",
            sk.slot_count().saturating_sub(1)
        ));
        if !sk.lines.is_empty() {
            out.push_str(&format!(
                "Dim sl{index}(0 To {}) As SldWorks.SketchLine\n",
                sk.lines.len() - 1
            ));
        }
        if !sk.circles.is_empty() {
            out.push_str(&format!(
                "Dim ci{index}(0 To {}) As SldWorks.SketchCircle\n",
                sk.circles.len() - 1
            ));
        }
    }
    out.push('\n');

    // ---- main ----
    out.push_str("Sub main()\n");
    out.push_str("    Dim template As String\n    Dim ok As Boolean\n    Dim st As String\n    Dim stopModel As Boolean\n    Dim stepIdx As Long\n");
    out.push_str("    stepIdx = -1\n    On Error GoTo Fail\n\n");
    out.push_str("    ' ---- report setup (before any model mutation) ----\n");
    out.push_str("    reportPath = ReportPathFromHost()\n");
    out.push_str("    If reportPath = \"\" Then Err.Raise vbObjectError + 513, \"craft-bridge\", \"no report path: CRAFT_BRIDGE_REPORT is unset and no path file exists in TEMP\"\n");
    out.push_str("    Open reportPath For Output As #1\n");
    let header_json = format!(
        "{{\"type\":\"header\",\"macro\":\"{}\",\"bridge_version\":\"{}\"}}",
        json_str_content(artifact),
        json_str_content(bridge_version)
    );
    out.push_str(&format!("    Print #1, {}\n", vb_lit(&header_json)));
    out.push_str("    FlushReport\n\n");

    for step in steps {
        out.push_str(&format!(
            "    ' ---- step {}: {} ----\n",
            step.index, step.command
        ));
        out.push_str(&format!("    stepIdx = {}\n", step.index));
        match &step.work {
            Work::Units { unit } => {
                out.push_str(&format!(
                    "    WriteStep stepIdx, {}, \"not-executed\", {}\n\n",
                    vb_lit(&step.command),
                    vb_lit(&format!(
                        "units recorded ({unit}); values replay in millimetres"
                    ))
                ));
            }
            Work::UserParam {
                name,
                equation_rhs,
                expect_si,
                ..
            } => {
                out.push_str("    If Not stopModel Then\n");
                out.push_str(&format!(
                    "        st = AddGlobalEquation({}, {}, {})\n",
                    vb_lit(name),
                    vb_lit(equation_rhs),
                    vba_num(*expect_si)
                ));
                out.push_str("    Else\n        st = \"not-executed\"\n        gMsg = \"after the first stopped step\"\n    End If\n");
                out.push_str(&format!(
                    "    WriteStep stepIdx, {}, st, gMsg\n    If st = \"failed\" Then stopModel = True\n\n",
                    vb_lit(&step.command)
                ));
            }
            Work::Note => {
                out.push_str(&format!(
                    "    WriteStep stepIdx, {}, \"not-executed\", {}\n\n",
                    vb_lit(&step.command),
                    vb_lit(&step.detail)
                ));
            }
            Work::Sketch(_) => {
                out.push_str("    If Not stopModel Then\n");
                out.push_str(&format!("        st = BuildSketch{}()\n", step.index));
                out.push_str("    Else\n        st = \"not-executed\"\n        gMsg = \"after the first stopped step\"\n    End If\n");
                out.push_str(&format!(
                    "    WriteStep stepIdx, {}, st, gMsg\n",
                    vb_lit(&step.command)
                ));
                out.push_str("    If st = \"failed\" Then stopModel = True\n\n");
            }
            Work::Extrude(_)
            | Work::Revolve(_)
            | Work::Primitive(_)
            | Work::Modifier(_)
            | Work::Pattern(_) => {
                out.push_str("    If Not stopModel Then\n");
                let kind = match &step.work {
                    Work::Extrude(_) => "Extrude",
                    Work::Revolve(_) => "Revolve",
                    Work::Primitive(_) => "Prim",
                    Work::Pattern(_) => "Pat",
                    _ => "Mod",
                };
                out.push_str(&format!("        st = Build{}{}()\n", kind, step.index));
                out.push_str("    Else\n        st = \"not-executed\"\n        gMsg = \"after the first stopped step\"\n    End If\n");
                out.push_str(&format!(
                    "    WriteStep stepIdx, {}, st, gMsg\n",
                    vb_lit(&step.command)
                ));
                out.push_str("    If st = \"failed\" Then stopModel = True\n\n");
            }
            Work::Unmappable => {
                out.push_str(&format!(
                    "    WriteStep stepIdx, {}, \"not-executed\", {}\n",
                    vb_lit(&step.command),
                    vb_lit(
                        "no translation yet; a fallback body lands with the hybrid-fallback ticket"
                    )
                ));
                out.push_str("    stopModel = True\n\n");
            }
            Work::AfterStop => {
                out.push_str(&format!(
                    "    WriteStep stepIdx, {}, \"not-executed\", {}\n\n",
                    vb_lit(&step.command),
                    vb_lit("after the first unmapped step")
                ));
            }
        }
    }

    out.push_str("    Print #1, \"{\"\"type\"\":\"\"summary\"\",\"\"status\"\":\"\"ok\"\"}\"\n");
    out.push_str("    Close #1\n    Exit Sub\n\n");
    out.push_str("Fail:\n");
    out.push_str("    ' The report must survive failure: open it if needed, write what happened\n");
    out.push_str("    ' and the completion signal, then leave the model as it is.\n");
    out.push_str("    On Error Resume Next\n");
    out.push_str("    If reportPath = \"\" Then reportPath = ReportPathFromHost()\n");
    out.push_str("    If reportPath <> \"\" Then\n");
    out.push_str("        Open reportPath For Append As #1\n");
    out.push_str("        Print #1, \"{\"\"type\"\":\"\"step\"\",\"\"index\"\":\" & Trim(Str(stepIdx)) & \",\"\"command\"\":\"\"macro\"\",\"\"status\"\":\"\"failed\"\",\"\"message\"\":\"\"\" & JsonStr(Err.Description) & \"\"\"}\"\n");
    out.push_str(
        "        Print #1, \"{\"\"type\"\":\"\"summary\"\",\"\"status\"\":\"\"failed\"\"}\"\n",
    );
    out.push_str("        Close #1\n    End If\nEnd Sub\n\n");

    // ---- per-sketch builders ----
    for (index, sk) in &sketches {
        out.push_str(&emit_sketch_subs(*index, sk));
    }
    for (index, ex) in &extrudes {
        out.push_str(&emit_extrude_subs(*index, ex));
    }
    let revolves: Vec<(usize, &crate::replay::RevolveStep)> = steps
        .iter()
        .filter_map(|s| match &s.work {
            Work::Revolve(rv) => Some((s.index, rv)),
            _ => None,
        })
        .collect();
    for (index, rv) in &revolves {
        out.push_str(&emit_revolve_subs(*index, rv));
    }
    let prims: Vec<(usize, &crate::replay::PrimStep)> = steps
        .iter()
        .filter_map(|s| match &s.work {
            Work::Primitive(p) => Some((s.index, p)),
            _ => None,
        })
        .collect();
    for (index, pr) in &prims {
        out.push_str(&emit_prim_subs(*index, pr));
    }
    let mods: Vec<(usize, &crate::replay::ModStep)> = steps
        .iter()
        .filter_map(|s| match &s.work {
            Work::Modifier(m) => Some((s.index, m)),
            _ => None,
        })
        .collect();
    for (index, md) in &mods {
        out.push_str(&emit_mod_subs(*index, md));
    }
    let pats: Vec<(usize, &crate::replay::PatStep)> = steps
        .iter()
        .filter_map(|s| match &s.work {
            Work::Pattern(p) => Some((s.index, p)),
            _ => None,
        })
        .collect();
    for (index, pt) in &pats {
        out.push_str(&emit_pat_subs(*index, pt));
    }

    // ---- shared helpers (the checkpoint's, unchanged in spirit) ----
    out.push_str(
        "' Write one step line and flush it to disk immediately.\n\
         Sub WriteStep(ByVal idx As Long, ByVal command As String, ByVal status As String, ByVal message As String)\n\
             On Error Resume Next\n\
             Print #1, \"{\"\"type\"\":\"\"step\"\",\"\"index\"\":\" & Trim(Str(idx)) & \",\"\"command\"\":\"\"\" & JsonStr(command) & \"\"\",\"\"status\"\":\"\"\" & JsonStr(status) & \"\"\",\"\"message\"\":\"\"\" & JsonStr(message) & \"\"\"}\"\n\
             FlushReport\n\
         End Sub\n\
\n\
         ' Close and reopen the report so the line just written reaches the disk.\n\
         Sub FlushReport()\n\
             On Error Resume Next\n\
             Close #1\n\
             Open reportPath For Append As #1\n\
         End Sub\n\
\n\
         ' The report path travels in the host's environment or in a one-line path\n\
         ' file under %%TEMP%%, because the macro runs inside the SolidWorks process.\n\
         Function ReportPathFromHost() As String\n\
             Dim p As String, f As Integer, oneLine As String\n\
             p = Environ$(\"CRAFT_BRIDGE_REPORT\")\n\
             If p <> \"\" Then\n\
                 ReportPathFromHost = p\n\
                 Exit Function\n\
             End If\n\
             p = Environ$(\"TEMP\")\n\
             If p = \"\" Then Exit Function\n\
             p = p & \"\\craft-bridge-report-path.txt\"\n\
             Err.Clear\n\
             On Error Resume Next\n\
             f = FreeFile\n\
             Open p For Input As #f\n\
             If Err.Number = 0 Then\n\
                 Line Input #f, oneLine\n\
                 Close #f\n\
                 If Err.Number = 0 Then ReportPathFromHost = Trim(oneLine)\n\
             End If\n\
         End Sub\n\
\n\
         ' JSON string escaping for the report file only.\n\
         Function JsonStr(ByVal s As String) As String\n\
             Dim t As String\n\
             t = Replace(s, \"\\\", \"\\\\\")\n\
             t = Replace(t, \"\"\"\", \"\\\"\")\n\
             t = Replace(t, vbCrLf, \"\\n\")\n\
             t = Replace(t, vbCr, \"\\n\")\n\
             t = Replace(t, vbLf, \"\\n\")\n\
             t = Replace(t, vbTab, \"\\t\")\n\
             JsonStr = t\n\
         End Function\n\
\n\
         ' Add a global-variable equation and rebuild. The name is a global, the\n\
         ' right-hand side is equation syntax. Globals are verified through the\n\
         ' dimensions that reference them.\n\
         Function AddGlobalEquation(ByVal nm As String, ByVal rhs As String, ByVal expect As Double) As String\n\
             On Error GoTo EqFail\n\
             Dim eqMgr As SldWorks.EquationMgr\n\
             Dim eqText As String\n\
             Set eqMgr = swDoc.GetEquationMgr\n\
             If eqMgr Is Nothing Then gMsg = \"the equation manager is missing\": AddGlobalEquation = \"failed\": Exit Function\n\
             eqText = \"\"\"\" & nm & \"\"\"=\" & rhs\n\
             eqMgr.Add2 -1, eqText\n\
             swDoc.EditRebuild3\n\
             gMsg = \"equation \" & eqText\n\
             AddGlobalEquation = \"created\"\n\
             Exit Function\n\
         EqFail:\n\
             gMsg = \"equation failed: \" & Err.Description\n\
             AddGlobalEquation = \"failed\"\n\
         End Function\n\
\n\
         ' Add an equation driving a dimension and verify it evaluated: the\n\
         ' dimension name is captured at runtime, the value must match the\n\
         ' expectation after a rebuild. Never presence alone.\n\
         Function AddDimEquation(ByVal dm As SldWorks.Dimension, ByVal rhs As String, ByVal expect As Double, ByVal slot As Long) As Boolean\n\
             On Error GoTo EqFail\n\
             Dim eqMgr As SldWorks.EquationMgr\n\
             Dim eqText As String\n\
             Set eqMgr = swDoc.GetEquationMgr\n\
             If eqMgr Is Nothing Then GoTo EqFail\n\
             eqText = \"\"\"\" & dm.Name & \"\"\"=\" & rhs\n\
             eqMgr.Add2 -1, eqText\n\
             swDoc.EditRebuild3\n\
             If Abs(dm.SystemValue - expect) > 0.000001 Then GoTo EqFail\n\
             If slot >= 0 Then regName(slot) = dm.Name
             AddDimEquation = True\n\
             Exit Function\n\
         EqFail:\n\
             AddDimEquation = False\n\
         End Function\n",
    );
    out
}

/// Per-sketch subs: BuildSketchN (orchestrator with the restore path),
/// DrawGeometryN, RelationsN, DimsN, VerifySketchN, CleanSketchN.
fn emit_sketch_subs(index: usize, sk: &SketchStep) -> String {
    let mut out = String::new();
    let initial_status = if sk.dropped_constraints.is_empty() {
        "created"
    } else {
        "degraded"
    };
    let initial_msg = if sk.dropped_constraints.is_empty() {
        format!(
            "{} relations and {} dimensions replayed",
            sk.relations.len(),
            sk.dimensions.len()
        )
    } else {
        format!(
            "constraints not replayed: {}",
            sk.dropped_constraints.join(", ")
        )
    };
    out.push_str(&format!("' Sketch step {index}: {}\n", vb_lit(&sk.name)));
    out.push_str(&format!(
        "Function BuildSketch{index}() As String\n    On Error GoTo HardFail\n    Dim ok As Boolean\n"
    ));
    out.push_str(&format!(
        "    ok = swDoc.Extension.SelectByID2({}, \"PLANE\", 0#, 0#, 0#, False, 0, Nothing, swSelectOption_e.swSelectOptionDefault)\n",
        vb_lit(plane_name(sk.plane))
    ));
    out.push_str(&format!(
        "    If Not ok Then gMsg = \"could not select the {} plane\": GoTo SketchFailed\n",
        plane_name(sk.plane)
    ));
    out.push_str(
        "    swSketchMgr.InsertSketch True\n    gSketchName = swSketchMgr.ActiveSketch.Name\n",
    );
    out.push_str(&format!("    DrawGeometry{index}\n"));
    out.push_str(&format!(
        "    If Not Relations{index}() Then GoTo Degrade\n    If Not Dims{index}() Then GoTo Degrade\n    If Not VerifySketch{index}() Then GoTo Degrade\n"
    ));
    out.push_str("    swSketchMgr.InsertSketch True\n");
    out.push_str(&format!(
        "    gMsg = {}\n    BuildSketch{index} = \"{}\"\n    Exit Function\n\n",
        vb_lit(&initial_msg),
        initial_status
    ));
    out.push_str(
        "Degrade:\n\
             ' Restore, do not merely delete relations: wipe the sketch contents,\n\
             ' redraw at the stored coordinates, reapply driving dimensions, verify again.\n\
             CleanSketch",
    );
    out.push_str(&format!(
        "{index}\n    DrawGeometry{index}\n    If Not Dims{index}() Then GoTo SketchFailed\n    If Not VerifySketch{index}() Then GoTo SketchFailed\n"
    ));
    out.push_str("    swSketchMgr.InsertSketch True\n");
    out.push_str(&format!(
        "    gMsg = \"rebuilt as geometry plus driving dimensions\"\n    BuildSketch{index} = \"degraded\"\n    Exit Function\n\n"
    ));
    out.push_str("SketchFailed:\n    On Error Resume Next\n    swSketchMgr.InsertSketch True\n");
    out.push_str(&format!(
        "    BuildSketch{index} = \"failed\"\n    Exit Function\n\nHardFail:\n    On Error Resume Next\n    swSketchMgr.InsertSketch True\n    gMsg = Err.Description\n    BuildSketch{index} = \"failed\"\nEnd Function\n\n"
    ));

    // DrawGeometry
    out.push_str(&format!("Sub DrawGeometry{index}()\n"));
    for (i, l) in sk.lines.iter().enumerate() {
        let a = sk.points[l.a];
        let b = sk.points[l.b];
        out.push_str(&format!(
            "    Set sl{index}({i}) = swSketchMgr.CreateLine({}, {}, 0#, {}, {}, 0#)\n",
            vba_num(mm(a[0])),
            vba_num(mm(a[1])),
            vba_num(mm(b[0])),
            vba_num(mm(b[1]))
        ));
        if l.construction {
            out.push_str(&format!("    sl{index}({i}).Construction = True\n"));
        }
        out.push_str(&format!(
            "    Set pt{index}({}) = sl{index}({i}).GetStartPoint\n    Set pt{index}({}) = sl{index}({i}).GetEndPoint\n",
            2 * i,
            2 * i + 1
        ));
    }
    for (j, c) in sk.circles.iter().enumerate() {
        let ctr = sk.points[c.c];
        out.push_str(&format!(
            "    Set ci{index}({j}) = swSketchMgr.CreateCircleByRadius({}, {}, 0#, {})\n",
            vba_num(mm(ctr[0])),
            vba_num(mm(ctr[1])),
            vba_num(mm(c.r))
        ));
        if c.construction {
            out.push_str(&format!("    ci{index}({j}).Construction = True\n"));
        }
        out.push_str(&format!(
            "    Set pt{index}({}) = ci{index}({j}).GetCenterPoint\n",
            2 * sk.lines.len() + j
        ));
    }
    out.push_str("    swDoc.ClearSelection2 True\nEnd Sub\n\n");

    // Relations
    out.push_str(&format!(
        "Function Relations{index}() As Boolean\n    On Error GoTo RelFail\n"
    ));
    for rel in &sk.relations {
        out.push_str(&emit_relation(index, rel));
    }
    out.push_str(&format!(
        "    Relations{index} = True\n    Exit Function\nRelFail:\n    Relations{index} = False\nEnd Function\n\n"
    ));

    // Dimensions
    out.push_str(&format!(
        "Function Dims{index}() As Boolean\n    On Error GoTo DimFail\n    Dim dd As SldWorks.DisplayDimension\n    Dim dm As SldWorks.Dimension\n"
    ));
    for (di, dim) in sk.dimensions.iter().enumerate() {
        out.push_str(&emit_dimension(index, dim, sk, equation_for(sk, di)));
    }
    out.push_str(&format!(
        "    Dims{index} = True\n    Exit Function\nDimFail:\n    Dims{index} = False\nEnd Function\n\n"
    ));

    // Verify
    out.push_str(&format!(
        "Function VerifySketch{index}() As Boolean\n    Const TOL As Double = 0.000001\n    On Error GoTo VerifyFail\n"
    ));
    for slot in 0..sk.slot_count() {
        let c = sk.slot_coord(slot);
        out.push_str(&format!(
            "    If Abs(pt{index}({slot}).X - {}) > TOL Then GoTo VerifyFail\n    If Abs(pt{index}({slot}).Y - {}) > TOL Then GoTo VerifyFail\n",
            vba_num(mm(c[0])),
            vba_num(mm(c[1]))
        ));
    }
    for (j, c) in sk.circles.iter().enumerate() {
        out.push_str(&format!(
            "    If Abs(ci{index}({j}).Radius - {}) > TOL Then GoTo VerifyFail\n",
            vba_num(mm(c.r))
        ));
    }
    out.push_str(&format!(
        "    VerifySketch{index} = True\n    Exit Function\nVerifyFail:\n    VerifySketch{index} = False\nEnd Function\n\n"
    ));

    // CleanSketch
    out.push_str(&format!(
        "Sub CleanSketch{index}()\n    Dim anySel As Boolean\n"
    ));
    out.push_str(&format!(
        "    If Not pt{index}(0) Is Nothing Then\n        pt{index}(0).Select False\n        anySel = True\n    End If\n"
    ));
    out.push_str("    swDoc.EditDelete\n    swDoc.ClearSelection2 True\nEnd Sub\n\n");
    out
}

fn emit_relation(index: usize, rel: &RelationT) -> String {
    let select_point = |slot: usize, append: bool| {
        format!(
            "    pt{index}({slot}).Select {}\n",
            if append { "True" } else { "False" }
        )
    };
    let select_line = |li: usize, append: bool| {
        format!(
            "    sl{index}({li}).Select {}\n",
            if append { "True" } else { "False" }
        )
    };
    let call = |c: &str| {
        format!("    swDoc.SketchAddConstraints \"{c}\"\n    swDoc.ClearSelection2 True\n")
    };
    match *rel {
        RelationT::PointsCoincident(a, b) => {
            select_point(a, false) + &select_point(b, true) + &call("sgCoincident")
        }
        RelationT::PointsHorizontal(a, b) => {
            select_point(a, false) + &select_point(b, true) + &call("sgHorizontal")
        }
        RelationT::PointsVertical(a, b) => {
            select_point(a, false) + &select_point(b, true) + &call("sgVertical")
        }
        RelationT::LineHorizontal(l) => select_line(l, false) + &call("sgHorizontal"),
        RelationT::LineVertical(l) => select_line(l, false) + &call("sgVertical"),
        RelationT::LinesParallel(a, b) => {
            select_line(a, false) + &select_line(b, true) + &call("sgParallel")
        }
        RelationT::LinesPerpendicular(a, b) => {
            select_line(a, false) + &select_line(b, true) + &call("sgPerpendicular")
        }
        RelationT::LinesTangent(a, b) => {
            select_line(a, false) + &select_line(b, true) + &call("sgTangent")
        }
        RelationT::LinesEqual(a, b) => {
            select_line(a, false) + &select_line(b, true) + &call("sgEqual")
        }
    }
}

fn equation_for(sk: &SketchStep, di: usize) -> Option<&crate::replay::DimEquation> {
    sk.dim_equations
        .iter()
        .find(|(i, _)| *i == di)
        .map(|(_, e)| e)
}

fn emit_dimension(
    index: usize,
    dim: &DimensionT,
    sk: &SketchStep,
    equation: Option<&crate::replay::DimEquation>,
) -> String {
    let mut out = String::new();
    // Selection of the referents.
    match dim.kind {
        DimKind::Length => out.push_str(&format!("    sl{index}({}).Select False\n", dim.a)),
        DimKind::Radius | DimKind::Diameter => {
            out.push_str(&format!("    ci{index}({}).Select False\n", dim.a))
        }
        DimKind::Angle => out.push_str(&format!(
            "    sl{index}({}).Select False\n    sl{index}({}).Select True\n",
            dim.a,
            dim.b.unwrap_or(0)
        )),
        _ => out.push_str(&format!(
            "    pt{index}({}).Select False\n    pt{index}({}).Select True\n",
            dim.a,
            dim.b.unwrap_or(0)
        )),
    }
    // Where the dimension is placed decides horizontal/vertical/aligned for
    // point pairs (documented in docs/mapping.md, pending seat verification).
    let (px, py): (f64, f64) = match dim.kind {
        DimKind::Length => {
            let a = sk.slot_coord(dim.a * 2);
            let b = sk.slot_coord(dim.a * 2 + 1);
            (
                mm((a[0] + b[0]) / 2.0) + 0.01,
                mm((a[1] + b[1]) / 2.0) + 0.01,
            )
        }
        DimKind::Radius | DimKind::Diameter => {
            let c = sk.points[sk.circles[dim.a].c];
            let r = sk.circles[dim.a].r;
            (mm(c[0] + r * 0.75), mm(c[1] + r * 0.75))
        }
        DimKind::Angle => (0.01, 0.01),
        _ => {
            let a = sk.slot_coord(dim.a);
            let b = sk.slot_coord(dim.b.unwrap_or(0));
            let (ax, ay) = (mm(a[0]), mm(a[1]));
            let (bx, by) = (mm(b[0]), mm(b[1]));
            match dim.kind {
                DimKind::DistanceX => ((ax + bx) / 2.0, ay - 0.01),
                DimKind::DistanceY => (ax + 0.01, (ay + by) / 2.0),
                _ => ((ax + bx) / 2.0 + 0.01, (ay + by) / 2.0 + 0.01),
            }
        }
    };
    out.push_str(&format!(
        "    Set dd = swDoc.AddDimension2({}, {}, 0#)\n    If dd Is Nothing Then GoTo DimFail\n    Set dm = dd.GetDimension2(0)\n    If dm Is Nothing Then GoTo DimFail\n",
        vba_num(px),
        vba_num(py)
    ));
    let si = match dim.kind {
        DimKind::Angle => dim.value, // already radians
        _ => mm(dim.value),
    };
    out.push_str(&format!("    dm.SystemValue = {}\n", vba_num(si)));
    if let Some(equation) = equation {
        out.push_str(&slot_guards(equation, "DimFail"));
        out.push_str(&format!(
            "    If Not AddDimEquation(dm, {}, {}, {}) Then GoTo DimFail\n",
            rhs_vba(equation),
            vba_num(equation.expect_si),
            equation.slot
        ));
    }
    out.push_str("    swDoc.ClearSelection2 True\n");
    out
}

fn emit_extrude_subs(index: usize, ex: &ExtrudeStep) -> String {
    use crate::replay::ExtrudeKind;
    let mut out = String::new();
    out.push_str(&format!("' Extrude step {index}: {}\n", vb_lit(&ex.name)));
    out.push_str(&format!(
        "Function BuildExtrude{index}() As String\n    On Error GoTo HardFail\n    Dim ok As Boolean\n    Dim feat As SldWorks.Feature\n    Dim dm As SldWorks.Dimension\n"
    ));
    out.push_str(&format!(
        "    ok = swDoc.Extension.SelectByID2(skName{}, \"SKETCH\", 0#, 0#, 0#, False, 0, Nothing, swSelectOption_e.swSelectOptionDefault)\n",
        ex.sketch_step
    ));
    out.push_str(
        "    If Not ok Then gMsg = \"could not select the sketch for the extrude\": GoTo ExFail\n",
    );
    let (call, verify, message) = match &ex.kind {
        ExtrudeKind::Blind { depth_m, negative } => (
            format!(
                "    Set feat = swDoc.FeatureManager.FeatureExtrusion2(True, False, {}, swEndConditions_e.swEndCondBlind, swEndConditions_e.swEndCondBlind, {}, 0#, False, False, False, False, 0#, 0#, False, False, False, False, True, True, True)\n",
                if *negative { "True" } else { "False" },
                vba_num(*depth_m)
            ),
            vec![(1usize, *depth_m)],
            format!("depth {} m", vba_num(*depth_m)),
        ),
        ExtrudeKind::Symmetric { total_m } => (
            format!(
                "    Set feat = swDoc.FeatureManager.FeatureExtrusion2(True, False, False, swEndConditions_e.swEndCondMidPlane, swEndConditions_e.swEndCondBlind, {}, 0#, False, False, False, False, 0#, 0#, False, False, False, False, True, True, True)\n",
                vba_num(*total_m)
            ),
            vec![(1, *total_m)],
            format!("symmetric, total {} m", vba_num(*total_m)),
        ),
        ExtrudeKind::TwoSided { first_m, second_m } => (
            format!(
                "    Set feat = swDoc.FeatureManager.FeatureExtrusion2(False, False, False, swEndConditions_e.swEndCondBlind, swEndConditions_e.swEndCondBlind, {}, {}, False, False, False, False, 0#, 0#, False, False, False, False, True, True, True)\n",
                vba_num(*first_m),
                vba_num(*second_m)
            ),
            vec![(1, *first_m), (2, *second_m)],
            format!("two-sided {} + {} m", vba_num(*first_m), vba_num(*second_m)),
        ),
        ExtrudeKind::ThroughAll { negative } => (
            format!(
                "    Set feat = swDoc.FeatureManager.FeatureExtrusion2(True, False, {}, swEndConditions_e.swEndCondThroughAll, swEndConditions_e.swEndCondBlind, 0#, 0#, False, False, False, False, 0#, 0#, False, False, False, False, True, True, True)\n",
                if *negative { "True" } else { "False" }
            ),
            vec![],
            "through all".to_string(),
        ),
    };
    out.push_str(&call);
    out.push_str(
        "    If feat Is Nothing Then gMsg = \"the extrude was not created\": GoTo ExFail\n",
    );
    // Each side's dimension is verified by validated lookup against the
    // evaluated expectation; through-all has no depth readback and says so.
    for (which, expected) in verify {
        out.push_str(&format!(
            "    Set dm = swDoc.Parameter(\"D{which}@\" & feat.Name)\n    If dm Is Nothing Then gMsg = \"the extrude dimension D{which} is missing\": GoTo ExFail\n    If Abs(dm.SystemValue - {}) > 0.000001 Then gMsg = \"the extrude dimension D{which} does not match\": GoTo ExFail\n",
            vba_num(expected)
        ));
    }
    if ex.equations.is_empty() && matches!(ex.kind, ExtrudeKind::ThroughAll { .. }) {
        out.push_str(
            "    ' through-all: the end condition is the geometry; depth readback does not apply\n",
        );
    }
    // Parametric depths become equations, verified by evaluation.
    for eq in &ex.equations {
        out.push_str(&slot_guards(eq, "ExFail"));
        out.push_str(&format!(
            "    Set dm = swDoc.Parameter(\"D{}@\" & feat.Name)\n    If dm Is Nothing Then gMsg = \"the extrude dimension D{} is missing\": GoTo ExFail\n    If Not AddDimEquation(dm, {}, {}, {}) Then gMsg = \"the extrude depth equation did not evaluate\": GoTo ExFail\n",
            eq.which,
            eq.which,
            rhs_vba(eq),
            vba_num(eq.expect_si),
            eq.slot
        ));
    }
    out.push_str(&format!(
        "    Set feat{index} = feat\n    gMsg = {}\n    BuildExtrude{index} = \"created\"\n    Exit Function\n\nExFail:\n    BuildExtrude{index} = \"failed\"\n    Exit Function\n\nHardFail:\n    On Error Resume Next\n    gMsg = Err.Description\n    BuildExtrude{index} = \"failed\"\nEnd Function\n\n",
        vb_lit(&message)
    ));
    out
}

/// Revolve builder: reopen the profile sketch only to draw and anchor a
/// helper axis when the axis is not already a line of the sketch, then select
/// the sketch plus the axis and call FeatureRevolve2. The revolve verifies
/// its angle dimension (validated lookup, evaluated expectation); sweep
/// direction and volume of partial revolves are acceptance checks (ticket #9).
fn emit_revolve_subs(index: usize, rv: &RevolveStep) -> String {
    use crate::replay::{DimEquation as DE, RevolveKind as RK};
    let mut out = String::new();
    out.push_str(&format!("' Revolve step {index}: {}\n", vb_lit(&rv.name)));
    out.push_str(&format!(
        "Function BuildRevolve{index}() As String\n    On Error GoTo HardFail\n    Dim ok As Boolean\n    Dim feat As SldWorks.Feature\n    Dim dm As SldWorks.Dimension\n    Dim ax As SldWorks.SketchLine\n"
    ));
    out.push_str(&format!(
        "    ok = swDoc.Extension.SelectByID2(skName{}, \"SKETCH\", 0#, 0#, 0#, False, 0, Nothing, swSelectOption_e.swSelectOptionDefault)\n",
        rv.sketch_step
    ));
    out.push_str(
        "    If Not ok Then gMsg = \"could not select the profile sketch\": GoTo ExFail\n",
    );
    match &rv.axis {
        AxisSel::Emitted { origin, dir } => {
            // Draw the helper axis inside the sketch, fix it so it cannot
            // drift, and leave the sketch again.
            let l = 0.05f64; // metres each way
            let (x1, y1) = (
                origin[0] / 1000.0 - dir[0] * l,
                origin[1] / 1000.0 - dir[1] * l,
            );
            let (x2, y2) = (
                origin[0] / 1000.0 + dir[0] * l,
                origin[1] / 1000.0 + dir[1] * l,
            );
            out.push_str("    swSketchMgr.InsertSketch True\n");
            out.push_str(&format!(
                "    Set ax = swSketchMgr.CreateLine({}, {}, 0#, {}, {}, 0#)\n",
                vba_num(x1),
                vba_num(y1),
                vba_num(x2),
                vba_num(y2)
            ));
            out.push_str("    ax.Construction = True\n");
            out.push_str("    ax.Select False\n");
            out.push_str("    swDoc.SketchAddConstraints \"sgFix\"\n");
            out.push_str("    swDoc.ClearSelection2 True\n");
        }
        AxisSel::Line(_) => {}
    }
    out.push_str("    swSketchMgr.InsertSketch True\n");
    // Select the sketch and the axis, then revolve.
    out.push_str(&format!(
        "    ok = swDoc.Extension.SelectByID2(skName{}, \"SKETCH\", 0#, 0#, 0#, False, 0, Nothing, swSelectOption_e.swSelectOptionDefault)\n",
        rv.sketch_step
    ));
    out.push_str(
        "    If Not ok Then gMsg = \"could not select the profile sketch\": GoTo ExFail\n",
    );
    match &rv.axis {
        AxisSel::Line(li) => out.push_str(&format!(
            "    If Not sl{}({li}).Select(True) Then gMsg = \"could not select the revolve axis\": GoTo ExFail\n",
            rv.sketch_step
        )),
        AxisSel::Emitted { .. } => out.push_str(
            "    If Not ax.Select(True) Then gMsg = \"could not select the helper axis\": GoTo ExFail\n",
        ),
    }
    let (call, verify, message) = match &rv.kind {
        RK::Blind { angle_rad, reverse } => (
            format!(
                "    Set feat = swDoc.FeatureManager.FeatureRevolve2(True, True, False, False, {}, True, swEndConditions_e.swEndCondBlind, swEndConditions_e.swEndCondBlind, {}, 0#, False, False, 0#, 0#, swThinWallType_e.swThinWallOneDirection, 0#, 0#, True, False, True)\n",
                if *reverse { "True" } else { "False" },
                vba_num(*angle_rad)
            ),
            vec![(1usize, *angle_rad)],
            format!("revolve {} deg", angle_rad.to_degrees()),
        ),
        RK::Symmetric { total_rad } => (
            format!(
                "    Set feat = swDoc.FeatureManager.FeatureRevolve2(True, True, False, False, False, True, swEndConditions_e.swEndCondMidPlane, swEndConditions_e.swEndCondBlind, {}, 0#, False, False, 0#, 0#, swThinWallType_e.swThinWallOneDirection, 0#, 0#, True, False, True)\n",
                vba_num(*total_rad)
            ),
            vec![(1, *total_rad)],
            format!("symmetric revolve {} deg total", total_rad.to_degrees()),
        ),
        RK::TwoSided { first_rad, second_rad } => (
            format!(
                "    Set feat = swDoc.FeatureManager.FeatureRevolve2(False, True, False, False, False, True, swEndConditions_e.swEndCondBlind, swEndConditions_e.swEndCondBlind, {}, {}, False, False, 0#, 0#, swThinWallType_e.swThinWallOneDirection, 0#, 0#, True, False, True)\n",
                vba_num(*first_rad),
                vba_num(*second_rad)
            ),
            vec![(1, *first_rad), (2, *second_rad)],
            format!(
                "two-sided revolve {} + {} deg",
                first_rad.to_degrees(),
                second_rad.to_degrees()
            ),
        ),
    };
    out.push_str(&call);
    out.push_str(
        "    If feat Is Nothing Then gMsg = \"the revolve was not created\": GoTo ExFail\n",
    );
    for (which, expected) in verify {
        out.push_str(&format!(
            "    Set dm = swDoc.Parameter(\"D{which}@\" & feat.Name)\n    If dm Is Nothing Then gMsg = \"the revolve angle dimension D{which} is missing\": GoTo ExFail\n    If Abs(dm.SystemValue - {}) > 0.000001 Then gMsg = \"the revolve angle D{which} does not match\": GoTo ExFail\n",
            vba_num(expected)
        ));
    }
    let equations: Vec<&DE> = rv.equations.iter().collect();
    for eq in equations {
        out.push_str(&slot_guards(eq, "ExFail"));
        out.push_str(&format!(
            "    Set dm = swDoc.Parameter(\"D{}@\" & feat.Name)\n    If dm Is Nothing Then gMsg = \"the revolve angle dimension D{} is missing\": GoTo ExFail\n    If Not AddDimEquation(dm, {}, {}, {}) Then gMsg = \"the revolve angle equation did not evaluate\": GoTo ExFail\n",
            eq.which,
            eq.which,
            rhs_vba(eq),
            vba_num(eq.expect_si),
            eq.slot
        ));
    }
    out.push_str(&format!(
        "    Set feat{index} = feat\n    gMsg = {}\n    BuildRevolve{index} = \"created\"\n    Exit Function\n\nExFail:\n    BuildRevolve{index} = \"failed\"\n    Exit Function\n\nHardFail:\n    On Error Resume Next\n    gMsg = Err.Description\n    BuildRevolve{index} = \"failed\"\nEnd Function\n\n",
        vb_lit(&format!("{message}; sweep direction and volume are acceptance checks"))
    ));
    out
}

/// Primitive builder: a generated sketch (rectangle or circle) on the Front
/// plane (XY) with driving dimensions and equations, then a blind extrude.
/// Placement is literal by design (this phase); sizes keep their parametrisation
/// through dimension equations.
fn emit_prim_subs(index: usize, pr: &crate::replay::PrimStep) -> String {
    use crate::replay::PrimKind;
    let mut out = String::new();
    out.push_str(&format!("' Primitive step {index}: {}\n", vb_lit(&pr.name)));
    out.push_str(&format!(
        "Function BuildPrim{index}() As String\n    On Error GoTo HardFail\n    Dim ok As Boolean\n    Dim feat As SldWorks.Feature\n    Dim dm As SldWorks.Dimension\n    Dim dd As SldWorks.DisplayDimension\n    Dim seg As Variant\n    Dim sl As SldWorks.SketchLine\n    Dim ci As SldWorks.SketchCircle\n"
    ));
    out.push_str("    ok = swDoc.Extension.SelectByID2(\"Front Plane\", \"PLANE\", 0#, 0#, 0#, False, 0, Nothing, swSelectOption_e.swSelectOptionDefault)\n");
    out.push_str("    If Not ok Then gMsg = \"could not select the Front plane\": GoTo ExFail\n");
    out.push_str("    swSketchMgr.InsertSketch True\n");
    let (ox, oy) = (pr.origin[0] / 1000.0, pr.origin[1] / 1000.0);
    match pr.kind {
        PrimKind::Box => {
            let l = pr.sizes[0].value / 1000.0;
            let w = pr.sizes[1].value / 1000.0;
            out.push_str(&format!(
                "    seg = swSketchMgr.CreateCornerRectangle({}, {}, 0#, {}, {}, 0#)\n",
                vba_num(ox),
                vba_num(oy),
                vba_num(ox + l),
                vba_num(oy + w)
            ));
            out.push_str("    Set sl = seg(0)\n    sl.Select False\n");
            out.push_str("    Set dd = swDoc.AddDimension2(0#, 0#, 0#)\n    If dd Is Nothing Then GoTo ExFail\n    Set dm = dd.GetDimension2(0)\n    If dm Is Nothing Then GoTo ExFail\n");
            out.push_str(&emit_size(1, &pr.sizes[0], "the box length"));
            out.push_str(
                "    swDoc.ClearSelection2 True\n    Set sl = seg(1)\n    sl.Select False\n",
            );
            out.push_str("    Set dd = swDoc.AddDimension2(0#, 0#, 0#)\n    If dd Is Nothing Then GoTo ExFail\n    Set dm = dd.GetDimension2(0)\n    If dm Is Nothing Then GoTo ExFail\n");
            out.push_str(&emit_size(2, &pr.sizes[1], "the box width"));
        }
        PrimKind::Cylinder => {
            let r = pr.sizes[0].value / 1000.0;
            out.push_str(&format!(
                "    Set ci = swSketchMgr.CreateCircleByRadius({}, {}, 0#, {})\n",
                vba_num(ox),
                vba_num(oy),
                vba_num(r)
            ));
            out.push_str("    ci.Select False\n");
            out.push_str("    Set dd = swDoc.AddDimension2(0#, 0#, 0#)\n    If dd Is Nothing Then GoTo ExFail\n    Set dm = dd.GetDimension2(0)\n    If dm Is Nothing Then GoTo ExFail\n");
            out.push_str(&emit_size(1, &pr.sizes[0], "the cylinder radius"));
        }
    }
    out.push_str("    swDoc.ClearSelection2 True\n    swSketchMgr.InsertSketch True\n");
    // The blind extrude carries the last size (height).
    let height = pr.sizes.last().map(|s| s.value / 1000.0).unwrap_or(0.0);
    out.push_str("    ok = swDoc.Extension.SelectByID2(swSketchMgr.ActiveSketch.Name, \"SKETCH\", 0#, 0#, 0#, False, 0, Nothing, swSelectOption_e.swSelectOptionDefault)\n");
    out.push_str(
        "    If Not ok Then gMsg = \"could not select the primitive sketch\": GoTo ExFail\n",
    );
    out.push_str(&format!(
        "    Set feat = swDoc.FeatureManager.FeatureExtrusion2(True, False, False, swEndConditions_e.swEndCondBlind, swEndConditions_e.swEndCondBlind, {}, 0#, False, False, False, False, 0#, 0#, False, False, False, False, True, True, True)\n",
        vba_num(height)
    ));
    out.push_str("    If feat Is Nothing Then gMsg = \"the primitive extrude was not created\": GoTo ExFail\n");
    out.push_str("    Set dm = swDoc.Parameter(\"D1@\" & feat.Name)\n    If dm Is Nothing Then gMsg = \"the primitive height dimension is missing\": GoTo ExFail\n");
    out.push_str(&format!(
        "    If Abs(dm.SystemValue - {}) > 0.000001 Then gMsg = \"the primitive height does not match\": GoTo ExFail\n",
        vba_num(height)
    ));
    if let Some(last) = pr.sizes.last() {
        out.push_str(&emit_size_eq(last, "the primitive height"));
    }
    out.push_str(&format!(
        "    gMsg = \"primitive created\"\n    BuildPrim{index} = \"created\"\n    Exit Function\n\nExFail:\n    BuildPrim{index} = \"failed\"\n    Exit Function\n\nHardFail:\n    On Error Resume Next\n    gMsg = Err.Description\n    BuildPrim{index} = \"failed\"\nEnd Function\n\n"
    ));
    out
}

/// Verify one primitive sketch size (dm already set) and attach its equation.
fn emit_size(_which: usize, size: &crate::replay::PrimSize, what: &str) -> String {
    let mm = size.value / 1000.0;
    let mut out = format!(
        "    If Abs(dm.SystemValue - {}) > 0.000001 Then gMsg = \"{} does not match\": GoTo ExFail\n",
        vba_num(mm),
        what
    );
    out.push_str(&emit_size_eq(size, what));
    out
}

fn emit_size_eq(size: &crate::replay::PrimSize, what: &str) -> String {
    match &size.equation {
        Some(eq) => {
            let mut out = slot_guards(eq, "ExFail");
            out.push_str(&format!(
            "    If Not AddDimEquation(dm, {}, {}, {}) Then gMsg = \"{} equation did not evaluate\": GoTo ExFail\n",
            rhs_vba(eq),
            vba_num(eq.expect_si),
            eq.slot,
            what
        ));
            out
        }
        None => String::new(),
    }
}

/// The right-hand side as a VBA string expression: static when the equation
/// has no segments, otherwise a concatenation with runtime dimension names.
fn rhs_vba(eq: &crate::replay::DimEquation) -> String {
    use crate::replay::RhsSeg;
    if eq.segs.is_empty() {
        return rhs_vba(eq);
    }
    let mut parts: Vec<String> = Vec::new();
    for seg in &eq.segs {
        match seg {
            RhsSeg::Text(t) => parts.push(vb_lit(t)),
            RhsSeg::Slot(slot) => parts.push(format!("(\"\"\"\" & regName({slot}) & \"\"\")")),
        }
    }
    parts.join(" & ")
}

/// Fail closed on dead slots: an equation may only reference a dimension
/// whose slot is live (registered after its own verification).
fn slot_guards(eq: &crate::replay::DimEquation, fail_label: &str) -> String {
    use crate::replay::RhsSeg;
    let mut out = String::new();
    for seg in &eq.segs {
        if let RhsSeg::Slot(slot) = seg {
            out.push_str(&format!(
                "    If regName({slot}) = \"\" Then GoTo {fail_label}\n"
            ));
        }
    }
    out
}

/// Modification features: coordinate-picked edges and faces (fail-closed
/// SelectByID2 with explicit types; recipe coordinates map identically into
/// the rebuilt model per docs/mapping.md) and one feature call each. The
/// five feature-call shapes are checkpoint-pending like every other API
/// member here: the seat loop corrects their exact argument lists.
fn emit_mod_subs(index: usize, md: &crate::replay::ModStep) -> String {
    use crate::replay::ModKind;
    let mut out = String::new();
    out.push_str(&format!(
        "' Modification step {index}: {}\n",
        vb_lit(&md.name)
    ));
    out.push_str(&format!(
        "Function BuildMod{index}() As String\n    On Error GoTo HardFail\n    Dim ok As Boolean\n    Dim feat As SldWorks.Feature\n    Dim dm As SldWorks.Dimension\n    Dim anySel As Boolean\n"
    ));
    // Selections first: every pick must land on the intended entity type.
    let (picks, pick_type) = match &md.kind {
        ModKind::Fillet { edges, .. } | ModKind::Chamfer { edges, .. } => (edges, "EDGE"),
        ModKind::Shell { faces, .. } | ModKind::Draft { faces, .. } => (faces, "FACE"),
        ModKind::Hole { at, .. } => (&vec![*at], "FACE"),
    };
    for (i, p) in picks.iter().enumerate() {
        let append = if i > 0 { "True" } else { "False" };
        out.push_str(&format!(
            "    ok = swDoc.Extension.SelectByID2(\"\", \"{pick_type}\", {}, {}, {}, {append}, 0, Nothing, swSelectOption_e.swSelectOptionDefault)\n",
            vba_num(p[0] / 1000.0),
            vba_num(p[1] / 1000.0),
            vba_num(p[2] / 1000.0)
        ));
        out.push_str(&format!(
            "    If Not ok Then gMsg = \"a {pick_type} pick did not land\": GoTo ExFail\n"
        ));
    }
    out.push_str("    anySel = True\n");
    // One feature call per family (argument lists: checkpoint-pending).
    match &md.kind {
        ModKind::Fillet {
            radius,
            tangent_chain,
            ..
        } => {
            out.push_str(&format!(
                "    ' feature call shape pending checkpoint verification\n    Set feat = swDoc.FeatureFillet3({}, {}, 0, 0, 0)\n",
                vba_num(radius / 1000.0),
                if *tangent_chain { "True" } else { "False" }
            ));
            out.push_str(&dim_check(1, radius / 1000.0, "the fillet radius"));
        }
        ModKind::Chamfer {
            distance,
            tangent_chain,
            ..
        } => {
            out.push_str(&format!(
                "    ' feature call shape pending checkpoint verification\n    Set feat = swDoc.FeatureChamfer3(0#, {}, {}, 0#, 0#, 0#, 0#, 0#, 0#, 0#, 0#)\n",
                vba_num(distance / 1000.0),
                vba_num(distance / 1000.0)
            ));
            let _ = tangent_chain;
            out.push_str(&dim_check(1, distance / 1000.0, "the chamfer distance"));
        }
        ModKind::Shell { thickness, .. } => {
            out.push_str(&format!(
                "    ' feature call shape pending checkpoint verification\n    Set feat = swDoc.FeatureShell({}, False, 0#, False, False, False, 0#, 0#, 0#, 0#, 0#)\n",
                vba_num(thickness / 1000.0)
            ));
            out.push_str(&dim_check(1, thickness / 1000.0, "the shell thickness"));
        }
        ModKind::Draft { angle_rad, .. } => {
            out.push_str(&format!(
                "    ' feature call shape pending checkpoint verification\n    Set feat = swDoc.FeatureDraft({}, False, 0#, 0#, False, False, False, 0#, 0#, 0#, 0#, 0#, 0#)\n",
                vba_num(*angle_rad)
            ));
            out.push_str(&dim_check(1, *angle_rad, "the draft angle"));
        }
        ModKind::Hole {
            diameter, depth, ..
        } => {
            let (endcond, d2) = match depth {
                Some(d) => ("swEndConditions_e.swEndCondBlind", vba_num(d / 1000.0)),
                None => ("swEndConditions_e.swEndCondThroughAll", "0#".to_string()),
            };
            out.push_str(&format!(
                "    ' feature call shape pending checkpoint verification\n    Set feat = swDoc.SimpleHole2(True, False, False, {endcond}, {}, {d2}, 0#, 0#, False, False, False, False, 0#, 0#)\n",
                vba_num(diameter / 1000.0)
            ));
            out.push_str(&dim_check(1, diameter / 1000.0, "the hole diameter"));
        }
    }
    out.push_str("    swDoc.ClearSelection2 True\n");
    for eq in &md.equations {
        out.push_str(&slot_guards(eq, "ExFail"));
        out.push_str(&format!(
            "    Set dm = swDoc.Parameter(\"D{}@\" & feat.Name)\n    If dm Is Nothing Then gMsg = \"the dimension D{} is missing\": GoTo ExFail\n    If Not AddDimEquation(dm, {}, {}, {}) Then gMsg = \"the equation did not evaluate\": GoTo ExFail\n",
            eq.which,
            eq.which,
            rhs_vba(eq),
            vba_num(eq.expect_si),
            eq.slot
        ));
    }
    let degrade_note = if md.degraded_variants.is_empty() {
        String::new()
    } else {
        format!(
            "; variants not replayed: {}",
            md.degraded_variants.join(", ")
        )
    };
    out.push_str(&format!(
        "    gMsg = {}\n    BuildMod{index} = \"{}\"\n    Exit Function\n\nExFail:\n    BuildMod{index} = \"failed\"\n    Exit Function\n\nHardFail:\n    On Error Resume Next\n    gMsg = Err.Description\n    BuildMod{index} = \"failed\"\nEnd Function\n\n",
        vb_lit(&format!("created{degrade_note}")),
        if md.degraded_variants.is_empty() { "created" } else { "degraded" }
    ));
    out
}

/// A validated dimension readback against the expected SI value.
fn dim_check(which: usize, expect: f64, what: &str) -> String {
    format!(
        "    If feat Is Nothing Then gMsg = \"the feature was not created\": GoTo ExFail\n    Set dm = swDoc.Parameter(\"D{which}@\" & feat.Name)\n    If dm Is Nothing Then gMsg = \"the {what} dimension is missing\": GoTo ExFail\n    If Abs(dm.SystemValue - {}) > 0.000001 Then gMsg = \"the {what} does not match\": GoTo ExFail\n",
        vba_num(expect)
    )
}

/// Mirrors about origin planes: the seeds are verified native features
/// (live bindings, fail-closed), the plane is selected like a sketch plane,
/// and the mirror call shape carries the checkpoint-pending mark.
fn emit_pat_subs(index: usize, pt: &crate::replay::PatStep) -> String {
    use crate::replay::{PatKind, RhsSeg};
    let _ = RhsSeg::Text(String::new());
    let mut out = String::new();
    out.push_str(&format!("' Pattern step {index}: {}\n", vb_lit(&pt.name)));
    out.push_str(&format!(
        "Function BuildPat{index}() As String\n    On Error GoTo HardFail\n    Dim ok As Boolean\n    Dim feat As SldWorks.Feature\n    Dim dm As SldWorks.Dimension\n"
    ));
    match &pt.kind {
        PatKind::Mirror { seeds, plane } => {
            // Live seed bindings first: never pattern a body that merely
            // stands in for a feature.
            for seed in seeds {
                out.push_str(&format!(
                    "    If feat{seed} Is Nothing Then gMsg = \"a seed feature did not verify\": GoTo ExFail\n"
                ));
            }
            let plane_name = match plane {
                crate::replay::OriginPlane::Xy => "Front Plane",
                crate::replay::OriginPlane::Xz => "Top Plane",
                crate::replay::OriginPlane::Yz => "Right Plane",
            };
            out.push_str(&format!(
                "    ok = swDoc.Extension.SelectByID2(\"{plane_name}\", \"PLANE\", 0#, 0#, 0#, False, 0, Nothing, swSelectOption_e.swSelectOptionDefault)\n"
            ));
            out.push_str(
                "    If Not ok Then gMsg = \"could not select the mirror plane\": GoTo ExFail\n",
            );
            for seed in seeds {
                out.push_str(&format!("    feat{seed}.Select True\n"));
            }
            out.push_str("    ' feature call shape pending checkpoint verification\n");
            out.push_str(
                "    Set feat = swDoc.FeatureManager.FeatureMirror(True, False, False, 0#, 0#)\n",
            );
            out.push_str(
                "    If feat Is Nothing Then gMsg = \"the mirror was not created\": GoTo ExFail\n",
            );
        }
        PatKind::Rectangular { .. } => {
            out.push_str("    gMsg = \"feature patterns await direction selection (ticket #6 remainder)\": GoTo ExFail\n");
        }
    }
    out.push_str("    swDoc.ClearSelection2 True\n");
    let degrade_note = if pt.degraded_variants.is_empty() {
        String::new()
    } else {
        format!(
            "; variants not replayed: {}",
            pt.degraded_variants.join(", ")
        )
    };
    out.push_str(&format!(
        "    gMsg = {}\n    BuildPat{index} = \"{}\"\n    Exit Function\n\nExFail:\n    BuildPat{index} = \"failed\"\n    Exit Function\n\nHardFail:\n    On Error Resume Next\n    gMsg = Err.Description\n    BuildPat{index} = \"failed\"\nEnd Function\n\n",
        vb_lit(&format!("created{degrade_note}")),
        if pt.degraded_variants.is_empty() { "created" } else { "degraded" }
    ));
    out
}
